const input=o=>({get:k=>o[k]??""});
function fixture(){
 const p=createProject(empty(),{name:"Source"}),q=createProject(p.state,{name:"Dependent"});
 let s=editProject(q.state,p.id,{startDate:"2026-11-01"});
 const resource=addPlanningResource(s,{label:"QA team",capacityPct:100,availableFrom:"2026-11-01",availableUntil:"2026-11-10"});
 s=resource.state;
 const a=createItem(s,p.id,{title:"Primary",assignee:"Alex",resourceId:resource.id,allocationPct:70});
 s=editItem(a.state,p.id,a.id,{estimateDays:3});
 const b=createItem(s,p.id,{title:"Secondary",assignee:"Different Alex",resourceId:resource.id,allocationPct:50});
 s=editItem(b.state,p.id,b.id,{estimateDays:4});
 const c=createItem(s,q.id,{title:"Downstream",assignee:"Alex",resourceId:resource.id,allocationPct:100});
 s=editItem(c.state,q.id,c.id,{estimateDays:2});
 s=addPortfolioLink(s,{from:p.id,to:q.id});
 return {state:s,source:p.id,dependent:q.id,first:a.id,second:b.id,third:c.id,resource:resource.id};
}
test("same resource ID aggregates load by capacity; names alone never unify people",()=>{
 const f=fixture(),before=serialize(f.state);
 const result=portfolioResources(f.state),r=result.people[0];
 assert.equal(result.totals.assignees,1);
 assert.equal(result.totals.openWork,3);
 assert.equal(r.itemCount,3);
 assert.equal(r.projectCount,2);
 assert.equal(r.overlapDays,3);
 assert.equal(r.maxConcurrent,2);
 assert.equal(r.maxLoadPct,120);
 assert.equal(r.overloadDays,3);
 assert.equal(r.unavailableDays,0);
 assert.equal(result.work.find(w=>w.id===f.third).startDate,"2026-11-05");
 assert.match(renderPortfolioResources(f.state),/QA team/);
 assert.match(renderProjectResources(f.state,f.source),/перегрузка/);
 assert.equal(serialize(f.state),before);
});
test("unlinked identical names are never counted as a committed resource",()=>{
 const p=createProject(empty(),{name:"Unknown"});
 const a=createItem(p.state,p.id,{title:"A",assignee:"Alex"});
 const b=createItem(a.state,p.id,{title:"B",assignee:"Alex"});
 const data=portfolioResources(b.state);
 assert.equal(data.totals.assignees,0);
 assert.equal(data.totals.unlinked,2);
 assert.equal(data.totals.undated,2);
 assert.equal(data.totals.potentialConflicts,0);
 assert.match(data.warning,/не являются проверенной личностью/);
});
test("capacity and explicit availability dates distinguish overload from outside window",()=>{
 const f=fixture();
 let s=editPlanningResource(f.state,f.resource,{label:"QA team",capacityPct:150,availableFrom:"2026-11-02",availableUntil:"2026-11-03"}).state;
 const r=portfolioResources(s).people[0];
 assert.equal(r.maxLoadPct,120);
 assert.equal(r.overloadDays,0);
 assert.ok(r.unavailableDays>0);
 assert.equal(portfolioResources(s).totals.outsideAvailability,1);
 assert.deepEqual(deserialize(serialize(s)),s);
});
test("state updates remain explicit, preserve old JSON and reject invalid allocation",()=>{
 const p=createProject(empty(),{name:"Legacy"});
 const a=createItem(p.state,p.id,{title:"Original"});
 const legacy=structuredClone(a.state);
 delete legacy.projects[0].items[0].resourceId;
 delete legacy.projects[0].items[0].allocationPct;
 assert.equal(validate(legacy),true);
 assert.equal(portfolioResources(legacy).totals.unlinked,1);
 assert.throws(()=>editItem(a.state,p.id,a.id,{resourceId:"forged"}),/resource commitment/);
 assert.throws(()=>editItem(a.state,p.id,a.id,{allocationPct:150}),/resource commitment/);
 assert.throws(()=>addPlanningResource(a.state,{label:"Invalid",capacityPct:0}),/Мощность/);
 const invalid=structuredClone(a.state);
 invalid.resources=[{id:"x",label:"QA",capacityPct:100,availableFrom:"2026-12-02",availableUntil:"2026-11-01"}];
 assert.throws(()=>validate(invalid),/planning resource/);
});
test("approved amendment changes workload and persists pinned resource identity",()=>{
 const f=fixture();
 const c=planChange(f.state,f.source,{title:"Extend work"});
 let s=setPlanWork(c.state,f.source,c.id,{itemId:f.first,estimateDays:7,assignee:"Alex",resourceId:f.resource,allocationPct:30}).state;
 const preview=previewPlanAmendment(s,f.source,c.id);
 assert.equal(preview.changed,2);
 assert.ok(preview.resourceRows.some(r=>r.id===f.resource));
 assert.equal(portfolioResources(s).byId.get(f.resource).maxLoadPct,120);
 s=decideChange(s,f.source,c.id,{status:"approved",rationale:"Approved after portfolio review"}).state;
 s=applyPlanAmendment(s,f.source,c.id).state;
 assert.equal(s.projects[0].items[0].allocationPct,30);
 assert.ok(s.projects[0].changes[0].planAppliedAt);
 assert.deepEqual(deserialize(serialize(s)),s);
});
test("resource form and linked work can be completed via existing editors",()=>{
 const p=createProject(empty(),{name:"Workspace"});
 let s=applyEditor(p.state,null,"resource-new",input({label:"Editor",capacityPct:"80",availableFrom:"2026-11-01",availableUntil:"2026-12-01"})).state;
 const resource=s.resources[0];
 assert.equal(resource.capacityPct,80);
 assert.match(editorSpec(null,"resource-edit:"+resource.id,s).title,/Изменить/);
 s=applyEditor(s,null,"resource-edit:"+resource.id,input({label:"Editor",capacityPct:"90",availableFrom:"2026-11-01",availableUntil:"2026-12-01"})).state;
 const created=applyEditor(s,p.id,"item",input({title:"Write report",estimateDays:"2",resourceId:resource.id,allocationPct:"40"}));
 s=created.state;
 assert.equal(s.projects[0].items[0].resourceId,resource.id);
 assert.equal(s.projects[0].items[0].allocationPct,40);
 assert.deepEqual(deserialize(serialize(s)),s);
});
test("HTML output escapes resource names and work titles",()=>{
 const p=createProject(empty(),{name:"<script>"});
 const r=addPlanningResource(p.state,{label:"<svg onload=alert(1)>",capacityPct:100});
 const t=createItem(r.state,p.id,{title:"<img src=x>",resourceId:r.id});
 const html=renderProjectResources(t.state,p.id)+renderPortfolioResources(t.state);
 assert.match(html,/&lt;img/);
 assert.match(html,/&lt;svg/);
 assert.doesNotMatch(html,/<svg onload/);
});
