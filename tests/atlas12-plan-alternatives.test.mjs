test('Application remains explicit, atomic and historical; second conflicting proposal becomes stale',()=>{
 const f=atlas12PlanAlternativesPortfolio(),original=serialize(f.snapshot);
 assert.throws(()=>applyPlanAmendment(f.snapshot,f.projectId,f.a),/утверждение/);
 const approved=decideChange(f.snapshot,f.projectId,f.a,{status:'approved',rationale:'Выбран вариант A'}).state;
 const preview=previewPlanAmendment(approved,f.projectId,f.a);
 assert.equal(approved.projects[0].items[0].resourceId,f.snapshot.projects[0].items[0].resourceId);
 const applied=applyPlanAmendment(approved,f.projectId,f.a).state;
 assert.equal(applied.projects[0].items[0].resourceId,f.liftId);
 assert.equal(applied.projects[0].items[3].resourceId,f.freeId);
 assert.equal(applied.projects[0].items[0].dueDate,f.snapshot.projects[0].items[0].dueDate);
 assert.deepEqual(applied.projects[0].planBaselines,approved.projects[0].planBaselines);
 assert.deepEqual(applied.projects[0].dependencies,approved.projects[0].dependencies);
 assert.deepEqual(applied.projects[1],approved.projects[1]);
 assert.equal(applied.projects[0].decisions.at(-1).kind,'plan_application');
 assert.equal(applied.projects[0].decisions.at(-1).changeId,f.a);
 assert.equal(portfolioSchedule(applied).byId.get(f.projectId).projectedFinish,preview.rows[0].afterFinish);
 assert.equal(portfolioResources(applied).totals.unlinked,0);
 assert.deepEqual(deserialize(serialize(applied)),applied);
 assert.throws(()=>applyPlanAmendment(applied,f.projectId,f.a),/применена/);
 assert.throws(()=>previewPlanAmendment(applied,f.projectId,f.b),/изменилась/);
 assert.equal(serialize(f.snapshot),original);
});
