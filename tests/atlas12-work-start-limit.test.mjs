test("Constraints survive ordinary approval, export and historical control points",async()=>{
 const f=fixture(),baseline=capturePlanBaseline(f.s,f.p,{name:"Исходный"});
 const proposal=planChange(baseline.state,f.p,{title:"Перенос отдельной работы"});
 const draft=setPlanWork(proposal.state,f.p,proposal.id,{itemId:f.b,estimateDays:2,notBeforeDate:"2026-11-25"}).state;
 const a=draft.projects[0].changes[0].planAmendments[0];
 assert.equal(a.before.notBeforeDate,null);assert.equal(a.after.notBeforeDate,"2026-11-25");
 assert.equal(previewPlanAmendment(draft,f.p,proposal.id).resourceAfter.overloadDays,0);
 assert.deepEqual(draft.projects[0].items,baseline.state.projects[0].items);
 assert.throws(()=>applyPlanAmendment(draft,f.p,proposal.id),/утвержд/);
 const approved=decideChange(draft,f.p,proposal.id,{status:"approved",rationale:"Допустимый перенос в резерве"}).state;
 const applied=applyPlanAmendment(approved,f.p,proposal.id).state;
 assert.equal(applied.projects[0].items.find(w=>w.id===f.b).notBeforeDate,"2026-11-25");
 const comparison=comparePlanBaseline(applied,f.p);
 assert.ok(comparison.rows.find(r=>r.id===f.b).reasons.includes("Изменено ограничение начала работы"));
 const newer=capturePlanBaseline(applied,f.p,{name:"Новая редакция"}).state;
 assert.equal(newer.projects[0].planBaselines[1].work.find(w=>w.id===f.b).notBeforeDate,"2026-11-25");
 assert.deepEqual(newer.projects[0].planBaselines[0],baseline.baseline);
 const {buildIwxaPortfolio,readIwxaPortfolio}=await import("../desktop/src/iwxa-portfolio.mjs");
 const bytes=await buildIwxaPortfolio(newer,{now:"2026-11-24T12:00:00.000Z"});
 assert.deepEqual((await readIwxaPortfolio(bytes)).snapshot,newer);
 const stale=editItem(draft,f.p,f.b,{notBeforeDate:"2026-11-26"});
 assert.throws(()=>previewPlanAmendment(stale,f.p,proposal.id),/Исходная работа изменилась/);
 const started=editItem(approved,f.p,f.b,{state:"in_progress",actualStartDate:"2026-11-23"});
 assert.throws(()=>applyPlanAmendment(started,f.p,proposal.id),/уже начатой/);
});
