function fixture(){
 const r=addPlanningResource(empty(),{label:"Монтажный участок",capacityPct:100});
 const p=createProject(r.state,{name:"Монтаж"});
 let s=editProject(p.state,p.id,{startDate:"2026-11-23",dueDate:"2026-12-10"});
 const add=(title,duration,options={})=>{
  const w=createItem(s,p.id,{title,...options});s=editItem(w.state,p.id,w.id,{estimateDays:duration});return w.id;
 };
 const a=add("Монтаж А",2,{resourceId:r.id,allocationPct:60});
 const b=add("Монтаж Б",2,{resourceId:r.id,allocationPct:60});
 const c=add("Приёмка",1);
 const critical=add("Подготовка площадки",6);
 s=addDependency(s,p.id,a,c);s=addDependency(s,p.id,b,c);
 return {s,p:p.id,a,b,c,critical,resource:r.id};
}
const row=(s,p,id)=>scheduleProject(s.projects.find(x=>x.id===p),{calendarLibrary:s.calendarLibrary??[],includeResourceOccupancy:true}).rows.find(w=>w.id===id);
test("An absolute Work start limit consumes reserve and moves successors, never invents a dependency",()=>{
 const f=fixture(),original=serialize(f.s);
 assert.equal(row(f.s,f.p,f.b).floatDays,3);
 const s=editItem(f.s,f.p,f.b,{notBeforeDate:"2026-11-25"});
 assert.equal(row(s,f.p,f.b).startDate,"2026-11-25");
 assert.equal(row(s,f.p,f.b).finishDate,"2026-11-27");
 assert.equal(row(s,f.p,f.b).floatDays,1);
 assert.equal(row(s,f.p,f.b).constraintWaitDays,2);
 assert.equal(row(s,f.p,f.c).startDate,"2026-11-27");
 assert.equal(portfolioSchedule(s).byId.get(f.p).projectedFinish,"2026-11-29");
 assert.equal(portfolioResources(f.s).byId.get(f.resource).overloadDays,2);
 assert.equal(portfolioResources(s).byId.get(f.resource).overloadDays,0);
 assert.deepEqual(s.projects[0].dependencies,f.s.projects[0].dependencies);
 assert.equal(serialize(f.s),original);
 assert.deepEqual(deserialize(serialize(s)),s);
 const cleared=editItem(s,f.p,f.b,{notBeforeDate:null});
 assert.deepEqual(cleared.projects[0].items,f.s.projects[0].items);
});
