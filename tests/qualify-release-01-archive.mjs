// Must receive the file produced with release/0.1 source, not a 0.2 snapshot.
import {readFileSync} from "node:fs";
import assert from "node:assert/strict";
import {empty,createProject,serialize,deserialize} from "../src/core.mjs";
import {prepareImportedSnapshot} from "../desktop/src/import-snapshot.mjs";

const archive=process.env.ATLAS_LEGACY_ARCHIVE;
if(!archive)throw Error("ATLAS_LEGACY_ARCHIVE must point to the actual release/0.1 JSON export");
const raw=readFileSync(archive,"utf8");
const imported=JSON.parse(raw);
const current=createProject(empty(),{name:"ATLAS_LOCAL_BEFORE_IMPORT"}).state;
const old=serialize(current);
const {snapshot,originalRevision,summary}=prepareImportedSnapshot(current,imported,"2026-11-03T00:00:00.000Z");
assert.equal(snapshot.schema,"atlas.project/1");
assert.equal(originalRevision,imported.revision);
assert.equal(snapshot.revision,Math.max(current.revision,imported.revision)+1);
assert.deepEqual(snapshot.projects,imported.projects);
assert.deepEqual(snapshot.portfolioLinks,imported.portfolioLinks);
assert.equal(snapshot.projects.length,2);
const first=snapshot.projects.find(p=>p.name==="ATLAS_LEGACY_01_RESEARCH");
const second=snapshot.projects.find(p=>p.name==="ATLAS_LEGACY_01_DELIVERY");
assert.ok(first&&second);
assert.equal(first.items.length,2);
assert.deepEqual(first.dependencies,[{from:first.items[0].id,to:first.items[1].id}]);
assert.equal(first.decisions[0].text,"ATLAS_LEGACY_01_HUMAN_DECISION");
assert.equal(first.findings[0].revision,"a".repeat(40));
assert.equal(first.findings[0].sourceId,first.sources[0].id);
assert.equal(first.changes[0].targetIds[0],first.targets[0].id);
assert.equal(snapshot.portfolioLinks[0].from,first.id);
assert.equal(snapshot.portfolioLinks[0].to,second.id);
assert.equal(snapshot.importProvenance.originalRevision,imported.revision);
assert.deepEqual(deserialize(serialize(snapshot)),snapshot);
assert.equal(serialize(current),old,"The current portfolio must remain untouched before explicit user approval");
assert.equal(summary.removed,1);
assert.equal(summary.incoming.projects,2);
assert.equal(summary.incoming.works,2);
assert.equal(summary.incoming.findings,1);
assert.equal(summary.incoming.decisions,1);
assert.equal(summary.incoming.changes,1);
assert.equal(summary.incoming.links,1);
console.log("ATLAS_RELEASE_01_TO_02_IMPORT_PASS originalRevision="+originalRevision+" importedRevision="+snapshot.revision);
