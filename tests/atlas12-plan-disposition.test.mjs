import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {empty,createProject,editProject,createItem,serialize,deserialize} from '../src/core.mjs';
import {planChange,decideChange,addTarget,compareProject} from '../src/trace.mjs';
import {setPlanWork,applyPlanAmendment} from '../src/plan-amendment.mjs';
import {portfolioSchedule} from '../src/portfolio-schedule.mjs';
import {responseState,portfolioResponses,changePlanningState,renderProjectResponses} from '../src/response.mjs';
import {projectImpact} from '../src/impact.mjs';
import {buildPortfolioCommand,renderPortfolioCommandRows} from '../src/portfolio-command.mjs';
import {realityOverview} from '../src/reality-overview.mjs';

function fixture(){
 const p=createProject(empty(),{name:'Planning',type:'engineering'});
 let s=editProject(p.state,p.id,{startDate:'2026-11-23',dueDate:'2026-12-10'});
 const target=addTarget(s,p.id,{title:'Expected result',desired:'Reviewed output'});s=target.state;
 const w=createItem(s,p.id,{title:'Existing Work',targetIds:[target.id]});
 s=w.state;
 const q=planChange(s,p.id,{title:'Adjust existing Work',targetIds:[target.id],causeKey:'target-review:'+target.id});
 s=setPlanWork(q.state,p.id,q.id,{itemId:w.id,estimateDays:3}).state;
 return {s,pid:p.id,tid:target.id,wid:w.id,cid:q.id};
}
const approve=(s,pid,cid)=>decideChange(s,pid,cid,{status:'approved',rationale:'Reviewed planning change'}).state;
const project=(s)=>s.projects[0];
test('Approved concrete plan is pending application, not missing a new Work, and disappears from pending on apply',()=>{
 const f=fixture(),original=serialize(f.s);
 let s=approve(f.s,f.pid,f.cid);
 const pending=portfolioSchedule(s);
 assert.deepEqual(pending.byId.get(f.pid).pendingPlanChanges,[f.cid]);
 assert.deepEqual(pending.byId.get(f.pid).unplannedChanges,[]);
 assert.equal(pending.totals.pendingPlans,1);
 assert.equal(pending.byId.get(f.pid).needsReview,true);
 const response=responseState(project(s),projectImpact(project(s)));
 assert.equal(response.pendingPlans,1);assert.equal(response.approvedWithoutWork,0);
 assert.match(renderProjectResponses(project(s),projectImpact(project(s))),/Рассмотреть утверждённый план/);
 const command=buildPortfolioCommand(s),row=command.rows.find(r=>r.id===f.pid);
 const action=row.signals.find(r=>r.panel==='changes');
 assert.equal(action.ref,f.cid);assert.match(action.label,/ожидает применения/);
 assert.equal(command.totals.pendingPlans,1);
 assert.match(renderPortfolioCommandRows(command),/inspect:.*:changes:/);
 s=deserialize(serialize(applyPlanAmendment(s,f.pid,f.cid).state));
 const applied=portfolioSchedule(s),r=applied.byId.get(f.pid);
 assert.deepEqual(r.pendingPlanChanges,[]);assert.deepEqual(r.unplannedChanges,[]);
 assert.deepEqual(r.appliedPlanChanges,[f.cid]);assert.equal(r.needsReview,false);
 assert.equal(applied.totals.appliedPlans,1);
 assert.equal(project(s).items.length,1);
 assert.equal(project(s).items[0].changeId,project(f.s).items[0].changeId);
 assert.ok(!project(s).items[0].changeId);
 const done=responseState(project(s),projectImpact(project(s)));
 assert.equal(done.pendingPlans,0);assert.equal(done.appliedPlans,1);assert.equal(done.approvedWithoutWork,0);
 assert.equal(buildPortfolioCommand(s).totals.pendingPlans,0);
 assert.ok(buildPortfolioCommand(s).rows[0].signals.every(x=>!x.label.includes('без связанных работ')));
 assert.equal(serialize(f.s),original);
});
test('Root cause has separate precise actions for a generic change and a concrete pending plan',()=>{
 const f=fixture();
 const s=approve(f.s,f.pid,f.cid);
 const q=planChange(s,f.pid,{title:'Another approved action',targetIds:[f.tid],causeKey:'target-review:'+f.tid});
 const both=approve(q.state,f.pid,q.id),p=project(both);
 const cause=responseState(p,projectImpact(p)).rows.find(r=>r.key==='target-review:'+f.tid);
 assert.deepEqual(cause.pendingPlanIds,[f.cid]);assert.deepEqual(cause.workMissingIds,[q.id]);
 assert.equal(cause.approvedWithoutWork,true);
 const reality=realityOverview(p,compareProject(p),projectImpact(p)).rows.find(r=>r.id===f.tid);
 assert.equal(reality.cause.activeChange.id,q.id);
 assert.equal(reality.cause.pendingPlanChangeId,f.cid);
 assert.equal(reality.cause.workMissingChangeId,q.id);
 const scheduled=portfolioSchedule(both).byId.get(f.pid);
 assert.deepEqual(scheduled.pendingPlanChanges,[f.cid]);assert.deepEqual(scheduled.unplannedChanges,[q.id]);
 const stats=portfolioResponses(both,projectImpact);assert.equal(stats.pendingPlans,1);assert.equal(stats.approvedWithoutWork,1);
});
test('Unbound approved plan appears in the portfolio queue without requiring a fabricated cause',()=>{
 const f=fixture();
 const q=planChange(f.s,f.pid,{title:'Independent plan correction'});
 let s=setPlanWork(q.state,f.pid,q.id,{itemId:f.wid,estimateDays:5}).state;
 s=approve(s,f.pid,q.id);
 const model=buildPortfolioCommand(s),signal=model.rows[0].signals.find(r=>r.panel==='changes');
 assert.equal(model.totals.pendingPlans,1);assert.equal(signal.ref,q.id);
 assert.equal(responseState(project(s),projectImpact(project(s))).pendingPlans,0);
 assert.equal(portfolioSchedule(s).totals.pendingPlans,1);
});
test('Legacy linked Work and applied plan states stay distinct, even if a Work happens to be linked',()=>{
 const linked=new Set(['c']);
 assert.equal(changePlanningState({id:'c',status:'approved'},linked),'work_linked');
 assert.equal(changePlanningState({id:'d',status:'approved'},linked),'work_missing');
 assert.equal(changePlanningState({id:'c',status:'approved',planAmendments:[{}]},linked),'plan_pending');
 assert.equal(changePlanningState({id:'c',status:'implemented',planAppliedAt:'2026-11-24T00:00:00Z'},linked),'plan_applied');
 assert.equal(changePlanningState({id:'c',status:'proposed',planAmendments:[{}]},linked),'inactive');
});
