test('Applied plan can progress to realized, but status cannot substitute for applying the actual plan',()=>{
 const f=atlas12PlanAlternativesPortfolio({includeSequence:true});
 const s=approve(f.snapshot,f.projectId,f.a);
 const running=applyEditor(s,f.projectId,'change:'+f.a,input({status:'in_progress',rationale:'Подготовка исполнения'})).state;
 assert.throws(()=>decideChange(running,f.projectId,f.a,{status:'implemented',rationale:'Недопустимо без применения'}),/Сначала примените/);
 assert.throws(()=>updateChange(running,f.projectId,f.a,'implemented'),/Сначала примените/);
 const applied=applyPlanAmendment(s,f.projectId,f.a).state;
 const spec=editorSpec(applied.projects[0],'change:'+f.a,applied);
 assert.deepEqual(spec.fields[0].options.map(x=>x.value),['in_progress']);
 const inProgress=applyEditor(applied,f.projectId,'change:'+f.a,input({status:'in_progress',rationale:'Исполнение утверждённого плана'})).state;
 const done=applyEditor(inProgress,f.projectId,'change:'+f.a,input({status:'implemented',rationale:'Корректировка реализована'})).state;
 assert.equal(row(done,f.projectId,f.a).status,'implemented');
 assert.deepEqual(done.projects[0].dependencies,applied.projects[0].dependencies);
 assert.equal(row(done,f.projectId,f.a).planAppliedAt,row(applied,f.projectId,f.a).planAppliedAt);
 assert.equal(done.projects[0].decisions.filter(d=>d.kind==='plan_application').length,1);
 assert.throws(()=>decideChange(applied,f.projectId,f.a,{status:'deferred',rationale:'Недопустимо'}),/Применённый план/);
});
